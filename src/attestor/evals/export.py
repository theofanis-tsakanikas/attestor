"""Generate tenant `lumen`'s evidence from the runs it describes.

`lumen`'s corpus documents Attestor itself, and two of its documents are about the eval
harnesses in this repository: an evaluation report and the data sheet describing the set that
report is measured on. Until now both were prose written by hand — accurate prose, but prose,
carrying a `content_sha256` computed over bytes that existed nowhere.

That is the one place in this repository where a figure's provenance loops back on itself. The
report claims a block rate; the corpus asserting it was typed by the same people who chose the
number. Nothing checks it, because there is nothing to check it against.

So these two documents are generated. `generate()` runs the harnesses — the real ones, the same
code paths `attestor eval injection` and `make ci` run — and writes what they returned. A
figure in the evaluation report is now the output of a run rather than a claim about one, and
`--check` fails the build when the committed export no longer matches what the harnesses do.

Deliberately deterministic: no timestamps, no run ids, no ordering that depends on a dict's
iteration. Two runs on the same tree produce identical bytes, which is what makes the digest in
the manifest mean anything at all.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from attestor.gates import abstention
from attestor.security import harness, isolation

#: The period `lumen`'s first technical file covers. Fixed, not derived from the clock: a
#: document that changes because a day passed cannot carry a stable digest.
PERIOD = "2026"
COVERS_FROM = "2026-01-01"
COVERS_TO = "2026-12-31"

EVALUATION_REPORT = "EVALREPORT-ATT-2026"
DATA_SHEET = "DATASHEET-ATT-2026"

_DOCUMENTS = "evidence/lumen/documents"


def _fence(rows: list[tuple[str, ...]], headers: tuple[str, ...]) -> str:
    """A markdown table. Plain, because the corpus is read by a retriever, not a browser."""
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def _ratio(numerator: int, denominator: int) -> str:
    return f"{numerator / denominator:.4f}" if denominator else "n/a"


def evaluation_report(root: Path) -> str:
    """The evaluation report — every figure in it produced by running the harness."""
    injection = harness.run(root / "evals" / "injection" / "corpus.yaml")
    refusals = abstention.run(root)
    tenants = isolation.run(root)

    poisoned = injection.poisoned
    benign = injection.benign
    blocked = injection.blocked
    false_positives = len(injection.false_positives)

    families = _fence(
        sorted(
            (outcome.case.note or "unclassified", "blocked" if outcome.detected else "MISSED")
            for outcome in poisoned
        ),
        ("Attack", "Outcome"),
    )

    return f"""---
document_id: {EVALUATION_REPORT}
document_class: evaluation_report
tenant: lumen
---

# Evaluation report — Attestor regulated reporting assistant

Monitoring period {COVERS_FROM} to {COVERS_TO}.

This document is generated by `attestor evidence export`. Every figure below is the return
value of a harness in this repository, run against the labelled sets in `evals/`. Nothing here
is transcribed from a summary, and `make ci` fails if this file stops matching what those
harnesses produce.

## 1. Robustness against manipulated input (Art. 15(5))

The system reads an untrusted evidence corpus. An attacker who can place a document in that
corpus can attempt to instruct the model through it. The scanner classifies each retrieved
passage; a flagged passage is withheld from the narrative turn and reported.

Measured on a held-out labelled set of {len(poisoned) + len(benign)} passages —
{len(poisoned)} carrying an injection attempt, {len(benign)} benign.

{
        _fence(
            [
                (
                    "Block rate on manipulated passages",
                    f"{blocked}/{len(poisoned)}",
                    _ratio(blocked, len(poisoned)),
                ),
                (
                    "False-positive rate on benign passages",
                    f"{false_positives}/{len(benign)}",
                    _ratio(false_positives, len(benign)),
                ),
                (
                    "Flagged for the wrong rule",
                    f"{len(injection.wrong_reason)}/{len(poisoned)}",
                    _ratio(len(injection.wrong_reason), len(poisoned)),
                ),
            ],
            ("Metric", "Count", "Value"),
        )
    }

A false positive is reported beside the block rate rather than below it. A detector that
withholds benign evidence degrades the disclosure it was meant to protect, so a block rate
quoted on its own is not a robustness figure — it is half of one.

### Outcome by attack family

{families}

## 2. Refusal discipline (Annex IV §2, Art. 13)

On corpora where evidence is deliberately absent, the system must decline to state the
datapoint, cite a reason code from a closed vocabulary, and state nothing else.

{
        _fence(
            [
                ("Refusals expected", str(refusals.expected_abstentions)),
                ("Refusals observed", str(refusals.observed_abstentions)),
                ("Figures stated without evidence", str(refusals.fabrications)),
                ("Scenarios exercised", str(len(refusals.results))),
            ],
            ("Metric", "Count"),
        )
    }

A fabrication is any disclosed figure on a datapoint whose evidence was withheld. The measured
count is the one number in this report that must be zero.

## 3. Separation between undertakings (Art. 15, Annex IV §2(b))

The system serves several undertakings from one deployment. Each probe below is a route by
which one undertaking's data could reach another's report.

{
        _fence(
            [
                (f"{result.number:>2}. {result.name}", "LEAK" if result.leaked else "closed")
                for result in tenants.results
            ],
            ("Probe", "Outcome"),
        )
    }

## 4. Limitations of this evaluation

The labelled sets are small and were written by the system's own authors. They establish that
the described controls operate and that a regression in them fails the build; they do not
establish a block rate against an adversary who has read them. The attack families in §1 are
those the authors anticipated, and an evaluation cannot measure the ones they did not.

The sets are held out in the sense that no detection rule is fitted to them — the rules are
written against the regulation and the threat model, not tuned until the corpus passes. They
are not held out in the stronger sense of having been drawn from traffic the authors never saw.

Accuracy of the underlying language model on a general benchmark is not reported here and is
not a property of this system: the model states no figure. What can be wrong is the prose
around a figure, which §2 and the provenance gate address, and the choice of evidence, which
§1 addresses.
"""


def data_sheet(root: Path) -> str:
    """The data sheet — what the sets in §1 and §2 of the evaluation report are made of."""
    cases = harness.load_corpus(root / "evals" / "injection" / "corpus.yaml")
    poisoned = [case for case in cases if case.poisoned]
    benign = [case for case in cases if not case.poisoned]
    refusals = abstention.run(root)

    return f"""---
document_id: {DATA_SHEET}
document_class: data_sheet
tenant: lumen
---

# Data sheet — evaluation sets

Monitoring period {COVERS_FROM} to {COVERS_TO}.

Generated by `attestor evidence export` from the sets themselves. Describes the data the
evaluation report is measured on, so that a reader can judge what those figures cover.

## Injection set

{
        _fence(
            [
                ("Passages", str(len(cases))),
                ("Carrying an injection attempt", str(len(poisoned))),
                ("Benign", str(len(benign))),
                ("Distinct attack families", str(len({case.note for case in poisoned}))),
                (
                    "Envelope-forgery cases",
                    str(sum(1 for case in poisoned if case.envelope_forgery)),
                ),
            ],
            ("Property", "Value"),
        )
    }

**Provenance.** Written by the system's authors against the threat model in ADR-0001 and the
manipulation techniques named in Art. 15(5). Not drawn from production traffic; this system has
no production traffic, and a corpus claiming otherwise would be the first thing an auditor
should disbelieve.

**Ground truth.** By construction. A passage's label is the list it is declared in, so there is
no annotator disagreement to report and no inter-rater statistic to quote.

**Held out.** No detection rule is fitted to these passages. Each rule is written against a
technique, and a rule added because a specific case failed would make this set training data —
which is why a new case that passes on the first run is recorded as such rather than celebrated.

**Benign set composition.** The benign passages are the ones a naive detector fails: supplier
correspondence that quotes an instruction, a methodology note describing what the system must
not do, a policy extract containing the word "ignore". A benign set of unrelated prose would
measure nothing.

### Attack families

{
        _fence(
            sorted((case.note or "unclassified", case.id) for case in poisoned),
            ("Family", "Case"),
        )
    }

## Abstention set

{
        _fence(
            [
                ("Scenarios", str(len(refusals.results))),
                ("Refusals expected across them", str(refusals.expected_abstentions)),
            ],
            ("Property", "Value"),
        )
    }

**Construction.** Each scenario removes or shifts evidence a datapoint requires, then asserts
both halves: that the affected datapoint is declined with a named reason code, and that every
other datapoint still resolves. A suite that only asserted the first half would pass on a
system that refused everything.
"""


#: What `generate()` produces, in the order it writes them.
EXPORTS: tuple[tuple[str, str], ...] = (
    (EVALUATION_REPORT, "evaluation_report"),
    (DATA_SHEET, "data_sheet"),
)

_BUILDERS = {EVALUATION_REPORT: evaluation_report, DATA_SHEET: data_sheet}


def _sidecar(document_id: str, document_class: str) -> str:
    """The metadata a Knowledge Base ingestion reads. Sorted, so the bytes are stable."""
    return (
        json.dumps(
            {
                "metadataAttributes": {
                    "document_class": document_class,
                    "document_id": document_id,
                    "period": PERIOD,
                    "tenant": "lumen",
                }
            },
            indent=2,
            sort_keys=True,
        )
        + "\n"
    )


def digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


MANIFEST = "evidence/lumen/2026.yaml"

#: Documents whose bytes live in this repository once generated. Their manifest entry pointed
#: at an S3 object that only exists while the estate is standing, which is why their declared
#: digest could never be checked and — as it turned out — had drifted from anything at all.
_LOCALISED = {document_id: f"{_DOCUMENTS}/{document_id}.md" for document_id, _ in EXPORTS}


def reconcile(root: Path | str = ".", *, check: bool = False) -> list[str]:
    """Make every locally-stored evidence document's manifest entry describe its actual bytes.

    `content_sha256` exists so that an auditor re-reads the same bytes rather than "the file".
    Three of `lumen`'s hand-written documents carried a digest of some earlier draft and nothing
    noticed, because nothing compared the two. This does, and `--check` makes the comparison a
    build failure rather than a note in a review nobody runs.

    Documents that genuinely live outside the repository — the risk-register and incident
    extracts, which are dumps of lake tables — keep their S3 URI and are reported as
    unverifiable rather than quietly skipped.
    """
    root = Path(root)
    path = root / MANIFEST
    lines = path.read_text(encoding="utf-8").splitlines(keepends=True)

    wanted: dict[str, tuple[str, str]] = {}
    for document_id, uri in _target_uris(root, lines).items():
        candidate = root / uri
        if not candidate.exists():
            continue
        wanted[document_id] = (uri, digest(candidate.read_text(encoding="utf-8")))

    changed: list[str] = []
    current: str | None = None
    for index, line in enumerate(lines):
        if (marker := line.strip()).startswith("- document_id:"):
            current = marker.split(":", 1)[1].strip()
            continue
        if current not in wanted:
            continue
        uri, want = wanted[current]
        for field, value in (("content_sha256", want), ("source_uri", uri)):
            prefix = f"    {field}: "
            if line.startswith(prefix) and line[len(prefix) :].strip() != value:
                changed.append(f"{current}.{field}")
                lines[index] = f"{prefix}{value}\n"

    if changed and not check:
        path.write_text("".join(lines), encoding="utf-8")
    return changed


def _target_uris(root: Path, lines: list[str]) -> dict[str, str]:
    """Where each document's bytes should be read from, generated ones relocated into the repo."""
    uris: dict[str, str] = {}
    current: str | None = None
    for line in lines:
        marker = line.strip()
        if marker.startswith("- document_id:"):
            current = marker.split(":", 1)[1].strip()
        elif current and marker.startswith("source_uri:"):
            uris[current] = _LOCALISED.get(current, marker.split(":", 1)[1].strip())
            current = None
    return uris


def unverifiable(root: Path | str = ".") -> list[str]:
    """Documents whose declared digest cannot be checked here, because the bytes are not here."""
    root = Path(root)
    lines = (root / MANIFEST).read_text(encoding="utf-8").splitlines(keepends=True)
    return sorted(
        document_id
        for document_id, uri in _target_uris(root, lines).items()
        if not (root / uri).exists()
    )


def generate(root: Path | str = ".", *, check: bool = False) -> list[str]:
    """Write the generated evidence, or report what is stale.

    Returns the repository-relative paths that differ. Empty means the committed exports are
    what the harnesses currently produce.
    """
    root = Path(root)
    stale: list[str] = []

    for document_id, document_class in EXPORTS:
        for relative, content in (
            (f"{_DOCUMENTS}/{document_id}.md", _BUILDERS[document_id](root)),
            (f"{_DOCUMENTS}/{document_id}.md.metadata.json", _sidecar(document_id, document_class)),
        ):
            path = root / relative
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current == content:
                continue
            stale.append(relative)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")

    return stale
